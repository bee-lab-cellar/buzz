import type {
  DspSoundtrackComposition,
  DspWaveShape,
  SoundtrackStepNote,
} from './dspChiptuneSynthesizer';

export function buildMelodyPattern(
  midis: ReadonlyArray<number>,
  steps = 2,
  velocity = 0.85,
): ReadonlyArray<SoundtrackStepNote> {
  return midis.map((midi) => ({ midi, steps, velocity }));
}

function makeTrack(
  index: number,
  id: string,
  title: string,
  arc: DspSoundtrackComposition['arc'],
  mood: DspSoundtrackComposition['mood'],
  bpm: number,
  filterCutoffHz: number,
  fmModIndex: number,
  leadWave: DspWaveShape,
  harmonyWave: DspWaveShape,
  leadMidis: ReadonlyArray<number>,
  harmonyMidis: ReadonlyArray<number>,
  bassMidis: ReadonlyArray<number>,
  drumPattern: string,
): DspSoundtrackComposition {
  return {
    id,
    index,
    title,
    arc,
    mood,
    bpm,
    filterCutoffHz,
    fmModIndex,
    leadWave,
    harmonyWave,
    leadPattern: buildMelodyPattern(leadMidis, 2, 0.88),
    harmonyPattern: buildMelodyPattern(harmonyMidis, 4, 0.62),
    bassPattern: buildMelodyPattern(bassMidis, 2, 0.9),
    drumPattern,
  };
}

