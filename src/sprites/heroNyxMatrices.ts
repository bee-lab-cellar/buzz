export function getNyxPalette(variantId: string, weaponTier: 1 | 2 | 3 | 4 | 5 = 2): Record<string, string> {
  const base = NYX_COAT_PALETTES.find((v) => v.id === variantId)?.palette ?? NYX_COAT_PALETTES[0].palette;
  const tier = NYX_WEAPON_TIERS.find((w) => w.tier === weaponTier) ?? NYX_WEAPON_TIERS[1];
  return {
    ...base,
    s: tier.bladeColor,
    a: tier.glowColor,
    w: tier.edgeColor,
    t: tier.hiltColor,
  };
}
