export function getLandmarkSpriteMatrix(landmarkId: string): StaticSpriteMatrix {
  if (LANDMARK_MATRICES_48X48[landmarkId]) {
    return LANDMARK_MATRICES_48X48[landmarkId];
  }
  switch (landmarkId) {
    case 'dwarven_magma_smeltery':
    case 'lava_anvil':
    case 'goblin_bonfire':
      return LANDMARK_MATRICES_48X48.dragon_beacon;
    case 'frozen_mammoth_skeleton':
    case 'ice_spire':
    case 'coral_arch':
    case 'sunken_galleon_mast':
    case 'drowned_bell_tower':
      return LANDMARK_MATRICES_48X48.wolf_fang_monolith;
    case 'lotus_shrine':
    case 'luminous_mushroom_shrine':
    case 'giant_hollow_oak':
      return LANDMARK_MATRICES_48X48.great_duck_statue;
    case 'spinning_watermill':
    case 'ruined_watchtower':
      return LANDMARK_MATRICES_48X48.clockwork_tower;
    case 'event_horizon_altar_299':
    case 'floating_star_forge_121':
      return LANDMARK_MATRICES_48X48.astral_obelisk;
    default:
      return LANDMARK_MATRICES_48X48.lion_sun_statue;
  }
}

export function getCapitalBuildingSpriteMatrix(id: CapitalBuildingId): StaticSpriteMatrix {
  return CAPITAL_BUILDING_MATRICES_24X24[id] ?? CAPITAL_BUILDING_MATRICES_24X24.royal_guild_hall;
}
